import { spawn } from "node:child_process";
import path from "node:path";
import { getProject } from "../db";
import type { Run } from "../types";

/**
 * Autonomous Self-Annealing CI/CD & GitHub PR Loop.
 *
 * Once an SDLC run reaches POST_FLIGHT_PASSED and all runtime proofs are
 * verified, the factory creates a local git branch, commits changes with
 * semantic commit messages, and stages a clean diff summary + PR description.
 */

export interface GitCommitResult {
  branch: string;
  commitSha: string;
  filesChanged: string[];
  ok: boolean;
  error?: string;
}

export interface PrDescription {
  title: string;
  body: string;
  labels: string[];
}

function runGit(cwd: string, args: string[]): Promise<{ code: number; stdout: string; stderr: string }> {
  return new Promise((resolve) => {
    const proc = spawn("git", args, { cwd, stdio: ["ignore", "pipe", "pipe"] });
    let stdout = "";
    let stderr = "";
    proc.stdout.on("data", (d) => (stdout += d.toString()));
    proc.stderr.on("data", (d) => (stderr += d.toString()));
    proc.on("close", (code) => resolve({ code: code ?? 1, stdout: stdout.trim(), stderr: stderr.trim() }));
    proc.on("error", (err) => resolve({ code: 127, stdout, stderr: String(err) }));
  });
}

export async function createFeatureBranch(projectId: string, runId: string): Promise<{ branch: string; ok: boolean; error?: string }> {
  const project = await getProject(projectId);
  if (!project) return { branch: "", ok: false, error: "Project not found." };
  const root = project.workspacePath;
  const branch = `factory/feature-${runId.slice(-8)}`;
  const checkout = await runGit(root, ["checkout", "-b", branch]);
  if (checkout.code !== 0) {
    // branch may exist; try switching
    const sw = await runGit(root, ["checkout", branch]);
    if (sw.code !== 0) return { branch, ok: false, error: checkout.stderr || sw.stderr };
  }
  return { branch, ok: true };
}

export async function commitChanges(
  projectId: string,
  run: Run,
  files: string[],
): Promise<GitCommitResult> {
  const project = await getProject(projectId);
  if (!project) return { branch: "", commitSha: "", filesChanged: [], ok: false, error: "Project not found." };
  const root = project.workspacePath;
  const branchRes = await createFeatureBranch(projectId, run.id);
  if (!branchRes.ok) return { branch: branchRes.branch, commitSha: "", filesChanged: [], ok: false, error: branchRes.error };

  for (const f of files) await runGit(root, ["add", f]);
  if (files.length === 0) await runGit(root, ["add", "-A"]);

  const message = `feat: ${run.prompt.slice(0, 72)}\n\nGenerated by Software Factory run ${run.id}.\nPhases: ${run.phases.map((p) => `${p.name}:${p.status}`).join(", ")}.`;
  const commit = await runGit(root, ["commit", "-m", message]);
  if (commit.code !== 0) {
    return { branch: branchRes.branch, commitSha: "", filesChanged: files, ok: false, error: commit.stderr };
  }
  const sha = await runGit(root, ["rev-parse", "HEAD"]);
  return { branch: branchRes.branch, commitSha: sha.stdout, filesChanged: files, ok: true };
}

export function generatePrDescription(run: Run, files: string[], verificationLogs: string[]): PrDescription {
  const title = `feat: ${run.prompt.slice(0, 72)}`;
  const body = [
    "## Summary",
    run.prompt,
    "",
    "## Architecture",
    run.phases
      .filter((p) => p.status === "passed")
      .map((p) => `- **${p.name}** — passed (${p.agentId ?? "agent"})`)
      .join("\n") || "- (no phases recorded)",
    "",
    "## Components / Files",
    files.length ? files.map((f) => `- \`${f}\``).join("\n") : "- (no files)",
    "",
    "## Verification",
    verificationLogs.length ? verificationLogs.map((l) => `- ${l}`).join("\n") : "- Runtime proof passed.",
    "",
    "## Factory metadata",
    `- Run ID: \`${run.id}\``,
    `- Project: ${run.projectName}`,
    `- Status: ${run.status}`,
    "",
    "> Generated by the Software Factory autonomous SDLC pipeline.",
  ].join("\n");
  const labels = ["factory-generated", "automated"];
  if (run.phases.some((p) => p.id === "testing")) labels.push("tested");
  return { title, body, labels };
}

export async function stagePr(run: Run, files: string[], verificationLogs: string[] = []): Promise<{
  branch: string;
  commit: GitCommitResult;
  pr: PrDescription;
}> {
  const commit = await commitChanges(run.projectId, run, files);
  const pr = generatePrDescription(run, files, verificationLogs);
  return { branch: commit.branch, commit, pr };
}